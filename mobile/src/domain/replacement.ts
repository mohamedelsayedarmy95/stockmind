/**
 * Replacing an operation that the server's history lost (Series 07, S1) - the client half.
 *
 * What the app may and may not do:
 * - It never re-sends a confirmed operation. The only way back is a NEW action chosen by a person, sent to the
 *   replacement endpoint, which the SERVER decides inside one transaction (original absent from the current history,
 *   generation current, access current, at most one replacement per original). The checks here only decide what to
 *   offer; they are not the guarantee.
 * - A review must be fresh: the person confirms what the server said a moment ago (REVIEW_TTL_MS), not an old screen.
 * - The replacement key is created once and persisted BEFORE the request leaves (beginReplacement). Every retry of the
 *   same decision reuses it; it is dropped only on an answer that proves nothing was recorded under it.
 * - "Absent" means absent from the current history. It is never described as "never happened".
 */
import {
  applyLookup, lookupRefs, OperationLookup, ReplacedRisk, ReplacementAttempt, ReplacementBlock, ReplacementBlockCode,
  resultOf, StockIntent,
} from './outbox';

/** A server check older than this is not a basis for a human decision any more. */
export const REVIEW_TTL_MS = 2 * 60_000;

/** What the review screen learned from the server about one lost operation. */
export interface ReviewSnapshot {
  intentId: string;
  /** The server's status of the original operation (the lookup of its key and receipt). */
  status: OperationLookup['status'];
  reason?: string;
  /** The company's history generation the answer is about. */
  generation: string;
  checkedAt: number;
}

export type ReplacementAvailability =
  | { available: true }
  | {
      available: false;
      reason:
        | 'not-lost' // the intent is not a history-changed review
        | 'no-receipt' // no movement id to name the original
        | 'attempt-in-progress' // a decision is already on its way
        | 'needs-check' // no server check yet
        | 'check-stale' // the check is too old
        | 'original-present' // the original is in the history now
        | 'indeterminate' // the server cannot tell: escalate to the manager/operator
        | 'unavailable' // the original is in a warehouse the user may no longer use
        | 'superseded'; // already replaced
    };

/** Whether to offer "Replace" now. Availability is advice for the screen; the server re-decides on submission. */
export function replacementAvailability(
  intent: StockIntent,
  review: ReviewSnapshot | null,
  now: number,
): ReplacementAvailability {
  if (intent.state !== 'NEEDS_REVIEW' || intent.lastError?.reason !== 'history-changed') return { available: false, reason: 'not-lost' };
  if (!intent.result?.movementId) return { available: false, reason: 'no-receipt' };
  if (intent.replacement && intent.replacement.state !== 'READY') return { available: false, reason: 'attempt-in-progress' };
  if (!review || review.intentId !== intent.id) return { available: false, reason: 'needs-check' };
  if (now - review.checkedAt > REVIEW_TTL_MS) return { available: false, reason: 'check-stale' };
  switch (review.status) {
    case 'absent':
      return { available: true };
    case 'present':
      return { available: false, reason: 'original-present' };
    case 'unavailable':
      return { available: false, reason: 'unavailable' };
    default:
      return { available: false, reason: review.reason === 'superseded' ? 'superseded' : 'indeterminate' };
  }
}

/**
 * The person confirmed. Creates the attempt with its key (generated by the caller) and the generation they reviewed.
 * Returns the intent unchanged when an attempt already exists: the key of a decision is never replaced.
 */
export function beginReplacement(
  intent: StockIntent,
  review: ReviewSnapshot,
  newKey: string,
  now: number,
): StockIntent {
  if (intent.replacement && intent.replacement.state !== 'READY') return intent;
  if (replacementAvailability(intent, review, now).available !== true) return intent;
  if (intent.replacement?.state === 'READY' && intent.replacement.expectedGeneration === review.generation) return intent;
  return {
    ...intent,
    replacementBlock: null,
    replacement: {
      key: newKey,
      expectedGeneration: review.generation,
      createdAt: now,
      attempts: 0,
      state: 'READY',
      lastError: null,
      result: null,
    },
  };
}

/** The HTTP request of an attempt. Deterministic: the same attempt always produces the same bytes (same hash). */
export function replacementRequest(intent: StockIntent): {
  path: string;
  idempotencyKey: string;
  body: Record<string, string | boolean>;
} | null {
  const a = intent.replacement;
  if (!a || !intent.result?.movementId) return null;
  const body: Record<string, string | boolean> = {
    originalKey: intent.id,
    originalMovementId: intent.result.movementId,
    productId: intent.payload.productId,
    warehouseId: intent.payload.warehouseId,
    quantity: intent.payload.quantity,
    expectedGeneration: a.expectedGeneration,
    acknowledge: true,
  };
  if (intent.result.revision) body.receiptRevision = intent.result.revision;
  if (intent.result.at) body.receiptConfirmedAt = new Date(intent.result.at).toISOString();
  if (intent.result.generation) body.receiptGeneration = intent.result.generation;
  return { path: `/stock/replacements/${intent.kind}`, idempotencyKey: a.key, body };
}

export function markReplacementSending(intent: StockIntent): StockIntent {
  const a = intent.replacement;
  if (!a || (a.state !== 'READY' && a.state !== 'UNKNOWN')) return intent;
  return { ...intent, replacement: { ...a, state: 'SENDING', attempts: a.attempts + 1 } };
}

export type ReplacementOutcome =
  | { ok: true; body: unknown }
  | { ok: false; status: number | undefined; code?: string | null; details?: Record<string, unknown> };

const BLOCK_CODES: readonly ReplacementBlockCode[] = [
  'stale-generation', 'original-present', 'original-indeterminate', 'original-unavailable', 'already-replaced',
  'insufficient-stock', 'in-progress',
];

/** What one answer (or the lack of one) does to the decision. */
export function settleReplacement(intent: StockIntent, outcome: ReplacementOutcome, now: number): StockIntent {
  const a = intent.replacement;
  if (!a || intent.state === 'REPLACED') return intent;

  if (outcome.ok) {
    const result = resultOf(outcome.body, now);
    return {
      ...intent,
      state: 'REPLACED',
      replacedRisk: null,
      replacementBlock: null,
      verification: null,
      replacement: { ...a, state: 'CONFIRMED', lastError: null, result },
    };
  }

  const { status } = outcome;
  const code = outcome.code ?? null;
  const error = { status: status ?? null, code, at: now };
  const keep = (state: 'READY' | 'UNKNOWN'): StockIntent => ({ ...intent, replacement: { ...a, state, lastError: error } });
  // Proof that nothing was recorded: the decision is dropped, its key with it, and the reason is shown.
  const refused = (blockCode: ReplacementBlockCode): StockIntent => ({
    ...intent,
    replacement: null,
    replacementBlock: { code: blockCode, at: now, ...(outcome.details ? { details: outcome.details } : {}) } as ReplacementBlock,
  });

  // No answer at all, or a gateway giving up: the server may have recorded it. Keep the key and say so.
  if (status === undefined || status === 408 || status >= 500) return keep('UNKNOWN');
  // Refused before anything ran: sign-in needed or rate limited. Same key, same request, later.
  if (status === 401 || status === 429) return keep('READY');

  if (status === 409 && code) {
    if (code === 'already-replaced') {
      // Another attempt of this same user recorded it: this is resolved; the lookup fills in the details.
      const key = typeof outcome.details?.replacementKey === 'string' ? outcome.details.replacementKey : a.key;
      const movementId = typeof outcome.details?.replacementMovementId === 'string' ? outcome.details.replacementMovementId : '';
      return {
        ...intent,
        state: 'REPLACED',
        replacedRisk: null,
        replacementBlock: null,
        verification: { state: 'pending', at: now },
        replacement: {
          ...a, key, state: 'CONFIRMED', lastError: error,
          result: { movementId, revision: null, runningBalance: null, replayed: false, at: now },
        },
      };
    }
    if ((BLOCK_CODES as readonly string[]).includes(code)) return refused(code as ReplacementBlockCode);
  }
  if (status === 403 || status === 404) return refused('no-access');
  if (status === 422) return refused('key-reused');
  return refused('invalid');
}

/** Whether the person may resend the SAME decision (same key, same bytes) from the review screen. */
export function canRetryReplacement(intent: StockIntent): boolean {
  const a = intent.replacement;
  return Boolean(a && (a.state === 'READY' || a.state === 'UNKNOWN'));
}

/** After an app kill: a request that was in flight may have been recorded. Same key; resolved by lookup or by retry. */
export function recoverReplacementAttempts(intents: readonly StockIntent[]): StockIntent[] {
  return intents.map((i) =>
    i.replacement?.state === 'SENDING' ? { ...i, replacement: { ...i.replacement, state: 'UNKNOWN' as const } } : i,
  );
}

/** Decisions whose outcome is unknown: asked about by THEIR key (read-only), never resent automatically. */
export function unresolvedAttempts(intents: readonly StockIntent[], scope: string): StockIntent[] {
  return intents.filter((i) => i.scope === scope && i.replacement?.state === 'UNKNOWN');
}

/**
 * The server's answer about the replacement's own key resolves an UNKNOWN decision:
 * - present → recorded: the operation is REPLACED;
 * - absent → nothing was recorded under the key: READY, to be resent by the person with the same key;
 * - anything else → still unknown.
 */
export function resolveAttempt(intent: StockIntent, lookup: OperationLookup, now: number): StockIntent {
  const a = intent.replacement;
  if (!a || a.state !== 'UNKNOWN' || lookup.key !== a.key) return intent;
  if (lookup.status === 'present' && lookup.movement) {
    return {
      ...intent,
      state: 'REPLACED',
      replacedRisk: null,
      replacementBlock: null,
      verification: null,
      replacement: {
        ...a,
        state: 'CONFIRMED',
        lastError: null,
        result: {
          movementId: lookup.movement.id, revision: lookup.movement.revision, runningBalance: null,
          replayed: false, at: now,
        },
      },
    };
  }
  if (lookup.status === 'absent') return { ...intent, replacement: { ...a, state: 'READY' } };
  return intent;
}

/** Evidence for a REPLACED operation: the original's and the replacement's own status in the current history. */
export function applyReplacedLookups(
  intent: StockIntent,
  original: OperationLookup | undefined,
  replacement: OperationLookup | undefined,
  now: number,
): StockIntent {
  if (intent.state !== 'REPLACED' || !intent.replacement) return intent;
  const origPresent = original?.status === 'present';
  const replPresent = replacement?.status === 'present';
  const replUnknown = !replacement || replacement.status === 'indeterminate' || replacement.status === 'unavailable';
  const risk = (r: ReplacedRisk | null): StockIntent => ({ ...intent, replacedRisk: r });

  if (origPresent && replPresent) return { ...risk('duplicate-risk'), verification: null };
  if (origPresent && !replUnknown) return { ...risk('replacement-missing'), verification: null };
  if (!origPresent && replPresent && replacement?.movement) {
    // The normal state: the original is gone from the history, its replacement is in it.
    return {
      ...intent,
      replacedRisk: null,
      verification: { state: 'verified', at: now },
      replacement: {
        ...intent.replacement,
        result: intent.replacement.result
          ? { ...intent.replacement.result, movementId: replacement.movement.id, revision: replacement.movement.revision }
          : intent.replacement.result,
      },
    };
  }
  if (original?.status === 'absent' && replacement?.status === 'absent') {
    // Both are gone (a later restore removed the replacement too): the history changed again. A person decides again.
    return {
      ...intent,
      state: 'NEEDS_REVIEW',
      lastError: { status: null, reason: 'history-changed', at: now },
      verification: null,
      replacement: null,
      replacedRisk: null,
      replacementBlock: null,
    };
  }
  return { ...intent, verification: { state: 'unverifiable', at: now, reason: replacement?.reason ?? original?.reason ?? 'unknown' } };
}

/** One entry point for a batch of server answers (by key): picks the right rule for each intent. */
export function applyLookups(intent: StockIntent, byKey: ReadonlyMap<string, OperationLookup>, now: number): StockIntent {
  const own = byKey.get(intent.id);
  const attempt = intent.replacement ? byKey.get(intent.replacement.key) : undefined;
  if (intent.state === 'REPLACED') return applyReplacedLookups(intent, own, attempt, now);
  let next = intent;
  if (attempt) next = resolveAttempt(next, attempt, now);
  if (own && next.state !== 'REPLACED') next = applyLookup(next, own, now);
  return next;
}

